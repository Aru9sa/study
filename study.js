'use strict';
const countryInput = document.getElementById('user-name');
const studyButton = document.getElementById('study');
const resultDivision = document.getElementById('result-area');
const tweetDivision = document.getElementById('tweet-area');

studyButton.addEventListener(
  'click',
  () => {
    const countryName = countryInput.value.trim();
    if (countryName.length === 0) {
      // 入力が空の時は処理を終了する
      return;
    }

    // 検索結果表示エリアの作成
    resultDivision.innerText = '';

const headerDivision = document.createElement('div');
    headerDivision.setAttribute('class', 'card-header text-bg-primary');
    headerDivision.innerText = 'おすすめポイント';

    // bodyDivision の作成
    const bodyDivision = document.createElement('div');
    bodyDivision.setAttribute('class', 'card-body');

    const paragraph = document.createElement('p');
    paragraph.setAttribute('class', 'card-text');
    const result = study(countryName);
    paragraph.innerText = result;
    bodyDivision.appendChild(paragraph);

    // resultDivision に Bootstrap のスタイルを適用する
    resultDivision.setAttribute('class', 'card');

    // headerDivision と bodyDivision を resultDivision に差し込む
    resultDivision.appendChild(headerDivision);
    resultDivision.appendChild(bodyDivision);

    // ツイートエリアの作成
    tweetDivision.innerText = '';
    const anchor = document.createElement('a');
    const hrefValue =
      'https://x.com/intent/tweet?button_hashtag=' +
      encodeURIComponent('あなたの好きな国は？') +
      '&ref_src=twsrc%5Etfw';

    anchor.setAttribute('href', hrefValue);
    anchor.setAttribute('class', 'twitter-hashtag-button');
    anchor.setAttribute('data-text', result);
    anchor.innerText = 'Tweet #あなたの好きな国は？';

    tweetDivision.appendChild(anchor);

    const script = document.createElement('script');
    script.setAttribute('src', 'https://platform.twitter.com/widgets.js');
    tweetDivision.appendChild(script);
  }
);

countryInput.addEventListener(
  'keydown',
  (event) => {
    if (event.key === 'Enter') {
      studyButton.dispatchEvent(new Event('click'));
    }
  }
);

