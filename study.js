/**
 * 国名の文字列を渡すとおすすめポイントを返す関数
 * @param {string} countryName 国名
 * @return {string} おすすめポイント
 */
function study(countryName) {
  if (countryData[countryName]) {
    return countryData[countryName];
  } else {
    return '「' + countryName + '」のデータはまだ登録されていません。日本、イタリア、フランス、アメリカなどを入力してみてください！';
  }
}
